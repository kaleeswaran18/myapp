const STORAGE_KEY = "vocab-learned-ids";

function speak(text, lang) {
  try {
    const synth = window.speechSynthesis;
    synth.cancel();
    const utter = new SpeechSynthesisUtterance(text);
    utter.lang = lang;
    utter.rate = 0.85;
    utter.pitch = 1;
    utter.volume = 1;

    const voices = synth.getVoices();
    const match = voices.find(v => v.lang === lang) || voices.find(v => v.lang.startsWith(lang.split("-")[0]));
    if (match) utter.voice = match;

    // Chrome bug: speak() right after cancel() can silently no-op; small delay fixes it
    setTimeout(() => synth.speak(utter), 60);
  } catch (e) {
    console.error("Speech failed", e);
  }
}

const SpeakerBtn = ({ text, lang, style }) => (
  <button
    onClick={(e) => { e.stopPropagation(); speak(text, lang); }}
    style={{ ...S.speakerBtn, ...style }}
    aria-label="pronounce"
  >
    🔊
  </button>
);

export default function VocabApp() {
  const [learned, setLearned] = useState(new Set());
  const [loaded, setLoaded] = useState(false);
  const [view, setView] = useState("home"); // home | deck | search
  const [activeCategory, setActiveCategory] = useState(null);
  const [deckIndex, setDeckIndex] = useState(0);
  const [flipped, setFlipped] = useState(false);
  const [query, setQuery] = useState("");
  const [toast, setToast] = useState("");
  const [direction, setDirection] = useState("en2ta"); // en2ta | ta2en

  // Load persisted progress from localStorage
  useEffect(() => {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (raw) {
        setLearned(new Set(JSON.parse(raw)));
      }
    } catch (e) {
      // no data yet
    }
    setLoaded(true);
  }, []);

  // Preload speech voices (some browsers load them async)
  useEffect(() => {
    if (typeof window !== "undefined" && window.speechSynthesis) {
      window.speechSynthesis.getVoices();
      window.speechSynthesis.onvoiceschanged = () => window.speechSynthesis.getVoices();
    }
  }, []);

  const persist = useCallback((nextSet) => {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify([...nextSet]));
    } catch (e) {
      console.error("Storage save failed", e);
    }
  }, []);

  const toggleLearned = useCallback((id) => {
    setLearned(prev => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id); else next.add(id);
      persist(next);
      return next;
    });
  }, [persist]);

  const deck = useMemo(() => {
    if (!activeCategory) return WORDS;
    return WORDS.filter(w => w.category === activeCategory);
  }, [activeCategory]);

  const searchResults = useMemo(() => {
    if (!query.trim()) return [];
    const q = query.trim().toLowerCase();
    return WORDS.filter(w => w.en.toLowerCase().includes(q) || w.ta.includes(query.trim()));
  }, [query]);

  const openDeck = (cat) => {
    setActiveCategory(cat);
    setDeckIndex(0);
    setFlipped(false);
    setView("deck");
  };

  const nextCard = (know) => {
    const w = deck[deckIndex];
    if (know !== null) {
      if (know && !learned.has(w.id)) toggleLearned(w.id);
      if (!know && learned.has(w.id)) toggleLearned(w.id);
    }
    setFlipped(false);
    if (deckIndex + 1 < deck.length) {
      setTimeout(() => setDeckIndex(i => i + 1), 120);
    } else {
      setToast("இந்த பிரிவு முடிந்தது! 🎉");
      setTimeout(() => setToast(""), 2200);
      setTimeout(() => setView("home"), 900);
    }
  };

  const learnedCount = learned.size;
  const totalCount = WORDS.length;
  const pct = Math.round((learnedCount / totalCount) * 100);

  if (!loaded) {
    return (
      <div style={S.loadingWrap}>
        <FontStyle />
        <div style={S.loadingText}>ஏற்றுகிறது…</div>
      </div>
    );
  }

  return (
    <div style={S.app}>
      <FontStyle />
      <div style={S.leafPattern} />

      <header style={S.header}>
        <div>
          <div style={S.kicker}>சொல் களஞ்சியம்</div>
          <h1 style={S.title}>Word Treasury</h1>
        </div>
        <div style={S.statPill}>
          <span style={S.statNum}>{learnedCount}</span>
          <span style={S.statSlash}>/</span>
          <span style={S.statTotal}>{totalCount}</span>
        </div>
      </header>

      <div style={S.progressTrack}>
        <div style={{ ...S.progressFill, width: `${pct}%` }} />
      </div>

      <nav style={S.tabBar}>
        {[
          ["home", "பிரிவுகள்"],
          ["search", "தேடல்"],
        ].map(([key, label]) => (
          <button
            key={key}
            onClick={() => setView(key)}
            style={{
              ...S.tabBtn,
              ...(view === key || (view === "deck" && key === "home") ? S.tabBtnActive : {}),
            }}
          >
            {label}
          </button>
        ))}
      </nav>

      {view === "home" && (
        <div style={S.grid}>
          {CATEGORIES.map(cat => {
            const items = WORDS.filter(w => w.category === cat);
            const done = items.filter(w => learned.has(w.id)).length;
            return (
              <button key={cat} style={S.catCard} onClick={() => openDeck(cat)}>
                <div style={S.catName}>{cat}</div>
                <div style={S.catMeta}>{done}/{items.length} கற்றது</div>
                <div style={S.catBarTrack}>
                  <div style={{ ...S.catBarFill, width: `${(done / items.length) * 100}%` }} />
                </div>
              </button>
            );
          })}
        </div>
      )}

      {view === "search" && (
        <div style={S.searchWrap}>
          <div style={S.dirToggle}>
            <button
              style={{ ...S.dirBtn, ...(direction === "en2ta" ? S.dirBtnActive : {}) }}
              onClick={() => setDirection("en2ta")}
            >
              English → தமிழ்
            </button>
            <button
              style={{ ...S.dirBtn, ...(direction === "ta2en" ? S.dirBtnActive : {}) }}
              onClick={() => setDirection("ta2en")}
            >
              தமிழ் → English
            </button>
          </div>
          <input
            style={S.searchInput}
            placeholder="English அல்லது தமிழ் தேடு..."
            value={query}
            onChange={e => setQuery(e.target.value)}
          />
          <div style={S.searchList}>
            {searchResults.map(w => (
              <div key={w.id} style={S.searchRow}>
                <div style={S.searchTextCol}>
                  {direction === "en2ta" ? (
                    <>
                      <div style={S.searchWordRow}>
                        <span style={S.searchEn}>{w.en}</span>
                        <SpeakerBtn text={w.en} lang="en-US" style={S.speakerSmall} />
                      </div>
                      <div style={S.searchWordRow}>
                        <span style={S.searchTa}>{w.ta}</span>
                        <SpeakerBtn text={w.ta} lang="ta-IN" style={S.speakerSmall} />
                      </div>
                    </>
                  ) : (
                    <>
                      <div style={S.searchWordRow}>
                        <span style={S.searchTa}>{w.ta}</span>
                        <SpeakerBtn text={w.ta} lang="ta-IN" style={S.speakerSmall} />
                      </div>
                      <div style={S.searchWordRow}>
                        <span style={S.searchEn}>{w.en}</span>
                        <SpeakerBtn text={w.en} lang="en-US" style={S.speakerSmall} />
                      </div>
                    </>
                  )}
                </div>
                <button
                  onClick={() => toggleLearned(w.id)}
                  style={{ ...S.miniCheck, ...(learned.has(w.id) ? S.miniCheckActive : {}) }}
                >
                  {learned.has(w.id) ? "✓" : ""}
                </button>
              </div>
            ))}
            {query.trim() && searchResults.length === 0 && (
              <div style={S.noResult}>எதுவும் கிடைக்கவில்லை</div>
            )}
          </div>
        </div>
      )}

      {view === "deck" && deck.length > 0 && (
        <div style={S.deckWrap}>
          <div style={S.deckHeader}>
            <button style={S.backBtn} onClick={() => setView("home")}>← பிரிவுகள்</button>
            <span style={S.deckCounter}>{deckIndex + 1} / {deck.length}</span>
          </div>

          <div style={S.dirToggle}>
            <button
              style={{ ...S.dirBtn, ...(direction === "en2ta" ? S.dirBtnActive : {}) }}
              onClick={() => { setDirection("en2ta"); setFlipped(false); }}
            >
              English → தமிழ்
            </button>
            <button
              style={{ ...S.dirBtn, ...(direction === "ta2en" ? S.dirBtnActive : {}) }}
              onClick={() => { setDirection("ta2en"); setFlipped(false); }}
            >
              தமிழ் → English
            </button>
          </div>

          <div style={S.cardStage} onClick={() => setFlipped(f => !f)}>
            <div style={{ ...S.card3d, transform: flipped ? "rotateY(180deg)" : "rotateY(0deg)" }}>
              <div style={S.cardFace}>
                <div style={S.cardCategory}>{deck[deckIndex].category}</div>
                {direction === "en2ta" ? (
                  <div style={S.cardWordRow}>
                    <div style={S.cardEn}>{deck[deckIndex].en}</div>
                    <SpeakerBtn text={deck[deckIndex].en} lang="en-US" />
                  </div>
                ) : (
                  <div style={S.cardWordRow}>
                    <div style={S.cardTa}>{deck[deckIndex].ta}</div>
                    <SpeakerBtn text={deck[deckIndex].ta} lang="ta-IN" />
                  </div>
                )}
                <div style={S.cardHint}>தட்டவும்</div>
              </div>
              <div style={{ ...S.cardFace, ...S.cardFaceBack }}>
                {direction === "en2ta" ? (
                  <div style={S.cardWordRow}>
                    <div style={S.cardTa}>{deck[deckIndex].ta}</div>
                    <SpeakerBtn text={deck[deckIndex].ta} lang="ta-IN" />
                  </div>
                ) : (
                  <div style={S.cardWordRow}>
                    <div style={S.cardEn}>{deck[deckIndex].en}</div>
                    <SpeakerBtn text={deck[deckIndex].en} lang="en-US" />
                  </div>
                )}
              </div>
            </div>
          </div>

          <div style={S.deckActions}>
            <button style={{ ...S.actionBtn, ...S.actionBtnNo }} onClick={() => nextCard(false)}>
              மீண்டும் பார்க்கணும்
            </button>
            <button style={{ ...S.actionBtn, ...S.actionBtnYes }} onClick={() => nextCard(true)}>
              தெரியும் ✓
            </button>
          </div>
        </div>
      )}

      {toast && <div style={S.toast}>{toast}</div>}
    </div>
  );
}

